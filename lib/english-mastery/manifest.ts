export const unitManifest: UnitMetadata[] = (
  Object.entries(titles) as [CefrLevel, string[]][]
).flatMap(([level, unitTitles]) =>
  unitTitles.map((title, index) => ({
    id: `${level}-${String(index + 1).padStart(2, "0")}`,
    level,
    sequence: index + 1,
    title,
  })),
);
export const pilotUnitIds = new Set([
  "A1-02",
  "A2-03",
  "B1-12",
  "B2-01",
  "C1-08",
  "C2-13",
]);
export const getUnit = (id: string) =>
  unitManifest.find((unit) => unit.id === id);
